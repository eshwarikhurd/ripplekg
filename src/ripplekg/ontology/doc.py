"""Renders docs/ontology.md from config/relations.yaml, config/nodes/ and config/relation_examples.yaml."""

from __future__ import annotations

from ripplekg.ontology.schema import NODE_FILES, PRIORS, Example, Ontology

FAMILY_TITLES = {
    "trade": "A. Trade links",
    "ownership_capital": "B. Ownership and capital",
    "footprint": "C. Physical footprint and materials",
    "competition": "D. Competition",
    "exposure": "E. External exposure",
    "disputes": "F. Disputes",
}
CHANNEL_TEXT = {
    "supply_chain": "supply chain",
    "both": "either kind of shock, either direction",
    "hub": "hub: shock reaches linked companies, never bridges companies",
    "competitive": "opposite sign (sign analysis only)",
    "event": "dated event, not a standing channel",
}


def _kinds(kinds: frozenset[str]) -> str:
    return " / ".join(sorted(kinds))


def _edge(e: dict) -> str:
    extra = []
    for key in ("material", "component", "hazard"):
        if key in e:
            extra.append(f"{key}={e[key]}")
    if "strength" in e:
        extra.append(f"strength={e['strength']} ({e['strength_basis']})")
    elif "strength_basis" in e:
        extra.append(f"strength basis={e['strength_basis']}")
    suffix = f" [{', '.join(extra)}]" if extra else ""
    return f"`{e['source']}` —{e['relation']}→ `{e['target']}`, {e['status']}{suffix}"


def render(ont: Ontology, examples: list[Example]) -> str:
    out = [
        "# Ontology",
        "",
        "Generated by `ripplekg ontology-doc` from [config/relations.yaml](../config/relations.yaml),",
        "[config/nodes/](../config/nodes/) and",
        "[config/relation_examples.yaml](../config/relation_examples.yaml).",
        "Edit those files, not this one.",
        "",
        "## Nodes",
        "",
        "Every node must resolve to a universe company or a curated list entry. Unresolved names are kept",
        "for review and never become nodes.",
        "",
        "| Kind | Count | Reference form | Source |",
        "|---|---|---|---|",
    ]
    counts = {}
    for n in ont.nodes.values():
        counts[n.kind] = counts.get(n.kind, 0) + 1
    out.append(
        f"| company | {counts.get('company', 0)} | `TSLA` | [universe.yaml](../config/universe.yaml) |"
    )
    for kind, filename in NODE_FILES.items():
        out.append(
            f"| {kind} | {counts.get(kind, 0)} | `{kind}:id` | [{filename}](../config/nodes/{filename}) |"
        )

    out += [
        "",
        "## Edge properties",
        "",
        f"- `status`: {', '.join(f'`{s}`' for s in ont.statuses)}",
        "- `valid_from`, `valid_to`: the period the relationship held, built from filing dates",
        "- `strength` in (0, 1] with a `strength_basis`, when a filing discloses a percentage",
        "- `confidence`, and the evidence: verbatim `quote`, accession number, filing date, form,",
        "  section and filer",
        "",
        "Strength bases:",
        "",
    ]
    out += [f"- `{k}`: {v}" for k, v in ont.strength_bases.items()]
    out += [
        "",
        "Fixed priors, used when no strength is disclosed (set before any data, not tuned): "
        + ", ".join(f"{k} = {v}" for k, v in PRIORS.items())
        + ".",
        "",
        "## Relations",
        "",
        "Supply-chain relations record which end is **upstream** (the supplier), whatever direction the",
        "relation name reads in. A supply shock flows upstream → downstream; a demand shock flows",
        "downstream → upstream.",
        "",
        f"{len(ont.relations)} canonical relations in {len(FAMILY_TITLES)} families. "
        "Extraction may also emit "
        + ", ".join(
            f"`{a}` (stored as `{r}`{' reversed' if rev else ''})"
            for a, (r, rev) in ont.relation_aliases.items()
        )
        + ".",
    ]
    for family, title in FAMILY_TITLES.items():
        out += [
            "",
            f"### {title}",
            "",
            "| Relation | Source → target | Channel | Prior | Meaning | When to use it |",
            "|---|---|---|---|---|---|",
        ]
        for rel in ont.relations.values():
            if rel.family != family:
                continue
            sym = " (symmetric)" if rel.symmetric else ""
            channel = CHANNEL_TEXT[rel.channel]
            if rel.upstream:
                channel += f" (upstream = {rel.upstream})"
            out.append(
                f"| `{rel.name}`{sym} | {_kinds(rel.source)} → {_kinds(rel.target)} | "
                f"{channel} | {rel.prior} | {rel.description} | {rel.guidance} |"
            )

    out += [
        "",
        "## Deduplication",
        "",
        "- Within a chunk, an exact repeat of (source, relation, target) is kept once. Symmetric relations",
        "  are stored with their endpoints in sorted order, so A↔B and B↔A are the same edge.",
        "- Exclusive groups list near-synonymous relations, most specific first. For the same pair of nodes",
        "  supported by the same quote, only the first relation of a group that appears is kept:",
        "",
    ]
    out += [f"  - **{g}**: {' > '.join(m)}" for g, m in ont.exclusive_groups.items()]
    out += [
        "",
        "- Across chunks and filings, repeated sightings of a fact are its evidence, not duplicates: the",
        "  graph builder merges them into one edge with a date range.",
        "- Companies are stored by ticker, other nodes by curated id, so name variants cannot create",
        "  duplicate nodes. Endpoints longer than 4 words are rejected.",
    ]
    out += [
        "",
        "## Examples",
        "",
        "Fictional companies. Each quote is checked to be a complete sentence copied verbatim from the text.",
        "",
    ]
    for ex in examples:
        out += [f"**{ex.relation}** (filer: {ex.filer})", "", f"> {ex.text}", ""]
        if ex.expect:
            out += [f"- {_edge(e)}" for e in ex.expect]
        else:
            out.append(f"- no edge: {ex.why}")
        out.append("")
    return "\n".join(out).rstrip() + "\n"
