"""docs/chunks.md: how much text reaches the LLM, and what extraction will cost.

Token counts are estimated as characters / 4; the week-5 pilot replaces them with measured usage.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import pandas as pd

from ripplekg.ingestion.chunking import ChunkStats

# Claude Haiku 5.5, USD per million tokens (prompts under 100K tokens), as of 2026-10.
HAIKU_INPUT_PER_M = 0.10
HAIKU_OUTPUT_PER_M = 0.50
BATCH_DISCOUNT = 0.5
PROMPT_OVERHEAD_TOKENS = 2_500  # ontology family definitions + examples, per call
OUTPUT_TOKENS_PER_CALL = 600  # JSON triples plus low-effort thinking
CHARS_PER_TOKEN = 4


@dataclass
class CostEstimate:
    calls: int
    input_tokens: int
    output_tokens: int

    @property
    def standard_usd(self) -> float:
        return (self.input_tokens * HAIKU_INPUT_PER_M + self.output_tokens * HAIKU_OUTPUT_PER_M) / 1e6

    @property
    def batch_usd(self) -> float:
        return self.standard_usd * BATCH_DISCOUNT


def estimate_cost(chunks: pd.DataFrame) -> CostEstimate:
    n_fam = chunks["families"].map(len)
    calls = int(n_fam.sum())
    chunk_tokens = (chunks["n_chars"] / CHARS_PER_TOKEN).round()
    input_tokens = int(((chunk_tokens + PROMPT_OVERHEAD_TOKENS) * n_fam).sum())
    return CostEstimate(calls, input_tokens, calls * OUTPUT_TOKENS_PER_CALL)


def _md(t: pd.DataFrame) -> str:
    cols = list(t.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(str(v) for v in row) + " |" for row in t.itertuples(index=False)]
    return "\n".join(lines)


def write_report(path: Path, chunks: pd.DataFrame, stats: ChunkStats) -> CostEstimate:
    selected = chunks[chunks["families"].map(len) > 0]
    cost = estimate_cost(selected)
    repeat_share = stats.repeated_lines / max(stats.content_lines, 1)
    novel_share = stats.chars_novel / max(stats.chars_in, 1)

    by_form = (
        chunks.assign(selected=chunks["families"].map(len) > 0)
        .groupby("form")
        .agg(chunks=("chunk_id", "count"), selected=("selected", "sum"))
        .reset_index()
    )
    fam_counts = (
        selected["families"].explode().value_counts().rename_axis("family").reset_index(name="chunks")
    )
    per_company = (
        selected.groupby("company_id")
        .agg(chunks=("chunk_id", "count"), calls=("families", lambda f: int(f.map(len).sum())))
        .sort_values("calls", ascending=False)
        .reset_index()
    )

    calls_per_chunk = cost.calls / max(len(selected), 1)
    text = f"""# Chunks and extraction cost

Generated by `ripplekg chunk`. Token counts are estimated at {CHARS_PER_TOKEN} characters per token; the
extraction pilot replaces these with measured usage.

## From documents to LLM calls

| Step | Value |
|---|---|
| Documents | {stats.documents:,} |
| Text lines in kept sections | {stats.lines:,} |
| Content lines (≥ 40 characters or table rows) | {stats.content_lines:,} |
| Repeated from an earlier filing of the same company | {stats.repeated_lines:,} ({repeat_share:.0%}) |
| Share of characters that are new | {novel_share:.0%} |
| Chunks built from new text | {len(chunks):,} |
| Chunks passing the keyword pre-filter | **{len(selected):,}** ({len(selected) / max(len(chunks), 1):.0%}) |
| LLM calls (one per tagged relation family) | **{cost.calls:,}** ({calls_per_chunk:.2f} per chunk) |

## Estimated cost with Claude Haiku 5.5

Assumes {PROMPT_OVERHEAD_TOKENS:,} prompt tokens and {OUTPUT_TOKENS_PER_CALL} output tokens per call, at
${HAIKU_INPUT_PER_M:.2f} / ${HAIKU_OUTPUT_PER_M:.2f} per million input / output tokens.

| | Value |
|---|---|
| Input tokens | {cost.input_tokens:,} |
| Output tokens | {cost.output_tokens:,} |
| Standard API | **${cost.standard_usd:,.2f}** |
| Batch API (50% off) | **${cost.batch_usd:,.2f}** |

## By form

{_md(by_form)}

## By relation family

{_md(fam_counts)}

## Calls per company

{_md(per_company)}
"""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    return cost
